/**
 * Compiles contracts/BatchExecutor.sol with solc-js and emits:
 *   - src/lib/generated/batchExecutor.ts  (typed ABI + bytecode for viem + deploy scripts)
 *   - artifacts/BatchExecutor.json        (raw compiler output)
 *
 * Run: bun run compile
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import solc from 'solc'

const root = resolve(import.meta.dir, '..')
const sourcePath = resolve(root, 'contracts/BatchExecutor.sol')
const source = readFileSync(sourcePath, 'utf8')

const input = {
  language: 'Solidity',
  sources: {
    'BatchExecutor.sol': { content: source },
  },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'prague',
    outputSelection: {
      '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object'] },
    },
  },
}

const output = JSON.parse(solc.compile(JSON.stringify(input))) as {
  errors?: Array<{ severity: string; formattedMessage: string }>
  contracts: Record<
    string,
    Record<string, { abi: unknown[]; evm: { bytecode: { object: string }; deployedBytecode: { object: string } } }>
  >
}

const errors = (output.errors ?? []).filter((e) => e.severity === 'error')
if (errors.length > 0) {
  for (const error of errors) console.error(error.formattedMessage)
  process.exit(1)
}

const contract = output.contracts['BatchExecutor.sol']?.BatchExecutor
if (!contract) throw new Error('BatchExecutor contract not found in compiler output')

const bytecode = contract.evm.bytecode.object
if (!bytecode) throw new Error('empty bytecode')

const generatedPath = resolve(root, 'src/lib/generated/batchExecutor.ts')
mkdirSync(dirname(generatedPath), { recursive: true })
writeFileSync(
  generatedPath,
  `// AUTO-GENERATED by scripts/compile.ts — do not edit by hand.
// Source: contracts/BatchExecutor.sol (solc ${solc.version()})

export const batchExecutorAbi = ${JSON.stringify(contract.abi, null, 2)} as const

export const batchExecutorBytecode = '0x${bytecode}' as const
`,
)

const artifactsPath = resolve(root, 'artifacts/BatchExecutor.json')
mkdirSync(dirname(artifactsPath), { recursive: true })
writeFileSync(
  artifactsPath,
  JSON.stringify(
    {
      contractName: 'BatchExecutor',
      solc: solc.version(),
      abi: contract.abi,
      bytecode: `0x${bytecode}`,
      deployedBytecode: `0x${contract.evm.deployedBytecode.object}`,
    },
    null,
    2,
  ),
)

console.log(`compiled BatchExecutor.sol with ${solc.version()}`)
console.log(`  abi       -> ${generatedPath}`)
console.log(`  bytecode  -> ${artifactsPath} (${bytecode.length / 2} bytes)`)
